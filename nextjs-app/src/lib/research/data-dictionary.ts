// that every field is visible in the current participant UI.

export type DictionarySection =
  | 'Account'
  | 'Core assessment'
  | 'Product intensity'
  | 'Behavioural context'
  | 'Safety'
  | 'Derived scores'
  | 'Research instruments'
  | 'Quit plan'
  | 'Follow-up'
  | 'Personal Digital Twin'

